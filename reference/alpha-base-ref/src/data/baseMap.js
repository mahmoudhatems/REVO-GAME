// بيبني قناع المشي (1 = ينفع يتمشى فيه) مرة واحدة وقت التشغيل
export function buildWalkMask() {
  const c = document.createElement('canvas');
  c.width = MAP_W; c.height = MAP_H;
  const ctx = c.getContext('2d', { willReadFrequently: true });
  ctx.fillStyle = '#000'; ctx.fillRect(0, 0, MAP_W, MAP_H);
  const fill = (polys, color) => {
    ctx.fillStyle = color;
    for (const p of polys) {
      ctx.beginPath();
      p.forEach(([x, y], i) => (i ? ctx.lineTo(x, y) : ctx.moveTo(x, y)));
      ctx.closePath(); ctx.fill();
    }
  };
  ctx.imageSmoothingEnabled = false;
  fill(WALK_POLYS, '#fff');
  fill(BLOCK_POLYS, '#000');
  const data = ctx.getImageData(0, 0, MAP_W, MAP_H).data;
  const mask = new Uint8Array(MAP_W * MAP_H);
  for (let i = 0; i < mask.length; i++) mask[i] = data[i * 4] > 127 ? 1 : 0;
  return mask;
}